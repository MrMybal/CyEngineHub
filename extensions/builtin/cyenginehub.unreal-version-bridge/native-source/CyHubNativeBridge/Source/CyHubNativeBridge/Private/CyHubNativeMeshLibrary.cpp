TSharedPtr<FJsonObject> Read(const FString& Path)
{ FString Text; TSharedPtr<FJsonObject> Json; return FFileHelper::LoadFileToString(Text, *Path) && FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(Text), Json) ? Json : nullptr; }
bool Write(const FString& Path, TSharedRef<FJsonObject> Json)
{ FString Text; FJsonSerializer::Serialize(Json, TJsonWriterFactory<>::Create(&Text)); return FFileHelper::SaveStringToFile(Text, *Path, FFileHelper::EEncodingOptions::ForceUTF8WithoutBOM); }
bool Valid(const FString& Path)
{ FString Package, Name; return Path.Split(TEXT("."), &Package, &Name) && Package.StartsWith(TEXT("/Game/")) && FPackageName::IsValidLongPackageName(Package) && Name == FPackageName::GetShortName(Package); }
bool CheckSections(const FMeshSectionInfoMap& Actual,const TSharedPtr<FJsonObject>& Fields,UStaticMesh* Mesh,TArray<TSharedPtr<FJsonValue>>& Adaptations,FString& Error)
{
    FMeshSectionInfoMap Expected;
    if(!CyHubObjectIO::ApplyStruct(FMeshSectionInfoMap::StaticStruct(),&Expected,Mesh,Fields,Adaptations,Error)||!CyHubObjectIO::CompareStruct(FMeshSectionInfoMap::StaticStruct(),&Expected,Mesh,Fields,Error))return false;
    TSet<uint32> Keys;for(auto Pair:Expected.Map)Keys.Add(Pair.Key);for(auto Pair:Actual.Map)Keys.Add(Pair.Key);
    // PostLoad rebuilds this map and can omit explicit entries equal to Get()'s defaults.
    // Compare effective material/collision/shadow/ray-tracing settings, including every extra target entry.
    for(uint32 Key:Keys)
    {
        auto Left=Expected.Get(Key>>16,Key&0xffff),Right=Actual.Get(Key>>16,Key&0xffff);FMeshSectionInfo Defaults;
        auto Values=CyHubObjectIO::StructProperties(FMeshSectionInfo::StaticStruct(),&Left,&Defaults,Mesh);
        if(!CyHubObjectIO::CompareStruct(FMeshSectionInfo::StaticStruct(),&Right,Mesh,Values,Error))return false;
    }
    return true;
}
bool Count(FArchive& Ar, int32& Value, int32 Maximum = 5000000)
{ Ar << Value; return !Ar.IsError() && Value >= 0 && Value <= Maximum; }
// Version-independent exchange: typed primitive arrays, not FMeshDescription::Serialize from the source engine.
bool Geometry(FMeshDescription& Mesh, FArchive& Ar)
{
    const bool Load = Ar.IsLoading(); FStaticMeshAttributes A(Mesh);
    if (Load) { Mesh.Empty(); A.Register(); }
    int32 Magic=0x43594831;Ar<<Magic;if(Magic!=0x43594831)return false;
    if(!Load)
    {
        auto Supported=[](const auto& Attributes)
        {
            TArray<FName> Names;Attributes.GetAttributeNames(Names);
            for(auto Name:Names)if(!FMeshAttributes::IsReservedAttributeName(Name)&&Name!=TEXT("Normal")&&Name!=TEXT("Tangent")&&Name!=TEXT("Binormal")&&Name!=TEXT("BinormalSign")&&Name!=TEXT("Color")&&Name!=TEXT("TextureCoordinate")&&Name!=TEXT("IsHard")&&Name!=TEXT("ImportedMaterialSlotName")&&Name!=TEXT("ObjectName")&&Name!=TEXT("CornerSharpness")&&Name!=TEXT("CreaseSharpness")&&Name!=TEXT("IsUVSeam")&&Name!=TEXT("Center")&&Name!=TEXT("EnableCollision")&&Name!=TEXT("CastShadow")){UE_LOG(LogTemp,Error,TEXT("Mesh attribute not transported: %s"),*Name.ToString());return false;}
            return true;
        };
        if(!Supported(Mesh.VertexAttributes())||!Supported(Mesh.VertexInstanceAttributes())||!Supported(Mesh.EdgeAttributes())||!Supported(Mesh.PolygonAttributes())||!Supported(Mesh.PolygonGroupAttributes())||!Supported(Mesh.TriangleAttributes()))return false;
    }
    bool ObjectNames=Mesh.PolygonAttributes().HasAttribute(TEXT("ObjectName"));Ar<<ObjectNames;if(Load&&ObjectNames)Mesh.PolygonAttributes().RegisterAttribute<FName>(TEXT("ObjectName"),1,NAME_None,EMeshAttributeFlags::AutoGenerated);
    bool Corner=Mesh.VertexAttributes().HasAttribute(TEXT("CornerSharpness"));Ar<<Corner;if(Load&&Corner)Mesh.VertexAttributes().RegisterAttribute<float>(TEXT("CornerSharpness"));
    bool Crease=Mesh.EdgeAttributes().HasAttribute(TEXT("CreaseSharpness"));Ar<<Crease;if(Load&&Crease)Mesh.EdgeAttributes().RegisterAttribute<float>(TEXT("CreaseSharpness"));
    bool Seam=Mesh.EdgeAttributes().HasAttribute(TEXT("IsUVSeam"));Ar<<Seam;if(Load&&Seam)Mesh.EdgeAttributes().RegisterAttribute<bool>(TEXT("IsUVSeam"));
    bool Collision=Mesh.PolygonGroupAttributes().HasAttribute(TEXT("EnableCollision"));Ar<<Collision;if(Load&&Collision)Mesh.PolygonGroupAttributes().RegisterAttribute<bool>(TEXT("EnableCollision"),1,true);
    bool Shadow=Mesh.PolygonGroupAttributes().HasAttribute(TEXT("CastShadow"));Ar<<Shadow;if(Load&&Shadow)Mesh.PolygonGroupAttributes().RegisterAttribute<bool>(TEXT("CastShadow"),1,true);
    TArray<FName> PolygonVectors;for(auto Key:{TEXT("Normal"),TEXT("Tangent"),TEXT("Binormal"),TEXT("Center")}){bool Has=Mesh.PolygonAttributes().HasAttribute(Key);Ar<<Has;if(Has){PolygonVectors.Add(FName(Key));if(Load)Mesh.PolygonAttributes().RegisterAttribute<FVector3f>(Key);}}
    auto Position = A.GetVertexPositions(); auto Normal = A.GetVertexInstanceNormals(); auto Tangent = A.GetVertexInstanceTangents();
    auto Sign = A.GetVertexInstanceBinormalSigns(); auto Color = A.GetVertexInstanceColors(); auto UV = A.GetVertexInstanceUVs();
    auto Slot = A.GetPolygonGroupMaterialSlotNames(); auto Hard = A.GetEdgeHardnesses();
    int32 Channels = UV.GetNumChannels(); if (!Count(Ar, Channels, 16)) return false; if (Load) UV.SetNumChannels(Channels);
    int32 N = Mesh.Vertices().Num(); if (!Count(Ar, N)) return false;
    if (Load) for (int32 I=0; I<N; ++I) { int32 Id; FVector3f P; Ar << Id << P; if (Id<0 || Id>5000000) return false; Mesh.CreateVertexWithID(FVertexID(Id)); Position[FVertexID(Id)] = P;if(Corner){float V;Ar<<V;Mesh.VertexAttributes().GetAttributesRef<float>(TEXT("CornerSharpness"))[FVertexID(Id)]=V;} }
    else for (auto Id : Mesh.Vertices().GetElementIDs()) { int32 Index=Id.GetValue(); FVector3f P=Position[Id]; Ar << Index << P;if(Corner){float V=Mesh.VertexAttributes().GetAttributesRef<float>(TEXT("CornerSharpness"))[Id];Ar<<V;} }
    N=Mesh.VertexInstances().Num(); if (!Count(Ar, N)) return false;
    auto Instance = [&](FVertexInstanceID Id)
    {
        FVector3f VNormal, VTangent; FVector4f VColor; float VSign;
        if (!Load) { VNormal=Normal[Id]; VTangent=Tangent[Id]; VColor=Color[Id]; VSign=Sign[Id]; }
        Ar << VNormal << VTangent << VColor << VSign;
        if (Load) { Normal[Id]=VNormal; Tangent[Id]=VTangent; Color[Id]=VColor; Sign[Id]=VSign; }
        for(int32 C=0; C<Channels; ++C) { FVector2f V; if(!Load) V=UV.Get(Id,C); Ar << V; if(Load) UV.Set(Id,C,V); }
    };
    if (Load) for(int32 I=0; I<N; ++I) { int32 Id, Vertex; Ar << Id << Vertex; if(Id<0 || Id>5000000 || !Mesh.Vertices().IsValid(FVertexID(Vertex))) return false; Mesh.CreateVertexInstanceWithID(FVertexInstanceID(Id),FVertexID(Vertex)); Instance(FVertexInstanceID(Id)); }
    else for(auto Id : Mesh.VertexInstances().GetElementIDs()) { int32 Index=Id.GetValue(), Vertex=Mesh.GetVertexInstanceVertex(Id).GetValue(); Ar << Index << Vertex; Instance(Id); }
    N=Mesh.PolygonGroups().Num(); if (!Count(Ar,N,65536)) return false;
    auto GroupExtras=[&](FPolygonGroupID Id){for(auto Key:{TEXT("EnableCollision"),TEXT("CastShadow")})if((Collision&&FString(Key)==TEXT("EnableCollision"))||(Shadow&&FString(Key)==TEXT("CastShadow"))){auto Ref=Mesh.PolygonGroupAttributes().GetAttributesRef<bool>(Key);bool V=Load?false:Ref[Id];Ar<<V;if(Load)Ref[Id]=V;}};
    if(Load) for(int32 I=0; I<N; ++I) { int32 Id; FString Name; Ar << Id << Name; if(Id<0 || Id>65536) return false; Mesh.CreatePolygonGroupWithID(FPolygonGroupID(Id)); Slot[FPolygonGroupID(Id)]=FName(*Name);GroupExtras(FPolygonGroupID(Id)); }
    else for(auto Id : Mesh.PolygonGroups().GetElementIDs()) { int32 Index=Id.GetValue(); FString Name=Slot[Id].ToString(); Ar << Index << Name;GroupExtras(Id); }
    N=Mesh.Polygons().Num(); if(!Count(Ar,N)) return false;
    if(Load) for(int32 I=0; I<N; ++I)
    {
        int32 Id, Group, V[3]; Ar << Id << Group << V[0] << V[1] << V[2];
        if(Id<0 || Id>5000000 || !Mesh.PolygonGroups().IsValid(FPolygonGroupID(Group))) return false;
        TArray<FVertexInstanceID> Instances; for(int32 J : V) { if(!Mesh.VertexInstances().IsValid(FVertexInstanceID(J))) return false; Instances.Add(FVertexInstanceID(J)); }
        Mesh.CreatePolygonWithID(FPolygonID(Id),FPolygonGroupID(Group),Instances);
        if(ObjectNames){FString ObjectName;Ar<<ObjectName;Mesh.PolygonAttributes().GetAttributesRef<FName>(TEXT("ObjectName"))[FPolygonID(Id)]=FName(*ObjectName);}
        for(auto Key:PolygonVectors){FVector3f VectorValue;Ar<<VectorValue;Mesh.PolygonAttributes().GetAttributesRef<FVector3f>(Key)[FPolygonID(Id)]=VectorValue;}
    }
    else for(auto Id : Mesh.Polygons().GetElementIDs())
    {
        auto Vertices=Mesh.GetPolygonVertexInstances(Id); if(Vertices.Num()!=3) return false;
        int32 Index=Id.GetValue(), Group=Mesh.GetPolygonPolygonGroup(Id).GetValue(); Ar << Index << Group;
        for(auto V : Vertices) { int32 IndexV=V.GetValue(); Ar << IndexV; }
        if(ObjectNames){FString ObjectName=Mesh.PolygonAttributes().GetAttributesRef<FName>(TEXT("ObjectName"))[Id].ToString();Ar<<ObjectName;}
        for(auto Key:PolygonVectors){FVector3f V=Mesh.PolygonAttributes().GetAttributesRef<FVector3f>(Key)[Id];Ar<<V;}
    }
    // Edge identity is topology-derived; canonical ordering makes source/target comparisons independent of edge allocation order.
    struct Edge { int32 A,B; bool Hard,Seam;float Crease; }; TArray<Edge> Edges;
    if(!Load) { for(auto Id : Mesh.Edges().GetElementIDs()) { auto V=Mesh.GetEdgeVertices(Id); Edges.Add({ FMath::Min(V[0].GetValue(),V[1].GetValue()),FMath::Max(V[0].GetValue(),V[1].GetValue()),Hard[Id],Seam?Mesh.EdgeAttributes().GetAttributesRef<bool>(TEXT("IsUVSeam"))[Id]:false,Crease?Mesh.EdgeAttributes().GetAttributesRef<float>(TEXT("CreaseSharpness"))[Id]:0 }); } Edges.Sort([](const Edge& L,const Edge& R){return L.A==R.A ? L.B<R.B : L.A<R.A;}); }
    N=Edges.Num(); if(!Count(Ar,N)) return false;
    if(Load) for(int32 I=0;I<N;++I) { Edge E; Ar << E.A << E.B << E.Hard;if(Seam)Ar<<E.Seam;if(Crease)Ar<<E.Crease; auto Id=Mesh.GetVertexPairEdge(FVertexID(E.A),FVertexID(E.B)); if(!Mesh.Edges().IsValid(Id)) return false; Hard[Id]=E.Hard;if(Seam)Mesh.EdgeAttributes().GetAttributesRef<bool>(TEXT("IsUVSeam"))[Id]=E.Seam;if(Crease)Mesh.EdgeAttributes().GetAttributesRef<float>(TEXT("CreaseSharpness"))[Id]=E.Crease; }
    else for(auto E : Edges){Ar << E.A << E.B << E.Hard;if(Seam)Ar<<E.Seam;if(Crease)Ar<<E.Crease;}
    return !Ar.IsError();
}
TSharedRef<FJsonObject> ModelProperties(FStaticMeshSourceModel& Model,UObject* Owner)
{
    FStaticMeshSourceModel Defaults;
    auto Fields=CyHubObjectIO::StructProperties(FStaticMeshSourceModel::StaticStruct(),&Model,&Defaults,Owner);
    // Import locations and old derived geometry counts are diagnostics, not target geometry/build inputs.
    for(auto Key : {TEXT("StaticMeshDescriptionBulkData"),TEXT("CacheMeshDescriptionTrianglesCount"),TEXT("CacheMeshDescriptionVerticesCount"),TEXT("SourceImportFilename")}) Fields->RemoveField(Key);
    return Fields;
}
TSharedRef<FJsonObject> MeshProperties(UStaticMesh* Mesh)
{
    auto Fields=CyHubObjectIO::Properties(Mesh);
    // The mesh material slots are not CPF_Edit in all engine revisions. They are essential
    // persistent data, not optional editor fields; transport them explicitly.
    auto All=CyHubObjectIO::Properties(Mesh,true);if(All->HasField(TEXT("StaticMaterials")))Fields->SetField(TEXT("StaticMaterials"),All->Values.FindChecked(TEXT("StaticMaterials")));
    for(auto Key : {TEXT("AssetImportData"),TEXT("ThumbnailInfo"),TEXT("BodySetup"),TEXT("Sockets")}) Fields->RemoveField(Key);
    return Fields;
}
bool Payload(const FString& Root,const TSharedPtr<FJsonObject>& Lod,FMeshDescription* Mesh,bool Import,FString& Error)
{
    const FString Name=Lod->GetStringField(TEXT("payload"));
    if(Name!=FPaths::GetCleanFilename(Name) || Name.Contains(TEXT("..")) || !Mesh) { Error=TEXT("Invalid mesh payload path/data"); return false; }
    TArray<uint8> Bytes;
    if(IFileManager::Get().FileSize(*(Root/Name)) > 1024LL*1024*1024 || !FFileHelper::LoadFileToArray(Bytes,*(Root/Name))) { Error=TEXT("Invalid mesh payload size");return false; }
    if(Import) { FMemoryReader Reader(Bytes); if(!Geometry(*Mesh,Reader) || Reader.Tell()!=Bytes.Num()) { Error=TEXT("Invalid mesh topology");return false; } }
    else { TArray<uint8> Actual; FMemoryWriter Writer(Actual); if(!Geometry(*Mesh,Writer) || Actual!=Bytes) { Error=TEXT("Mesh geometry/topology/normals/tangents/colors/UV/hard-edge mismatch");return false; } }
    return true;
}
bool Snapshot(UStaticMesh* Mesh,const FString& Root,TSharedRef<FJsonObject> Entry,FString& Error)
{
    if(!Mesh || Mesh->GetClass()!=UStaticMesh::StaticClass()) {Error=TEXT("Exact StaticMesh required");return false;}
    if(Mesh->SpeedTreeWind.IsValid()) {Error=TEXT("SpeedTree wind native state requires its own adapter");return false;}
    Entry->SetStringField(TEXT("path"),Mesh->GetPathName()); Entry->SetObjectField(TEXT("properties"),MeshProperties(Mesh));
    FAssetCompilingManager::Get().FinishAllCompilation();
    TArray<TSharedPtr<FJsonValue>> RenderLods;
    if(!Mesh->GetRenderData()){Error=TEXT("Source render geometry unavailable");return false;}
    for(auto& Lod:Mesh->GetRenderData()->LODResources){auto Stat=MakeShared<FJsonObject>();Stat->SetNumberField(TEXT("vertices"),Lod.GetNumVertices());Stat->SetNumberField(TEXT("triangles"),Lod.GetNumTriangles());RenderLods.Add(MakeShared<FJsonValueObject>(Stat));}
    Entry->SetArrayField(TEXT("renderLODs"),RenderLods);Entry->SetBoolField(TEXT("naniteData"),Mesh->HasValidNaniteData());
    TArray<TSharedPtr<FJsonValue>> Lods;
    for(int32 I=0;I<Mesh->GetNumSourceModels();++I)
    {
        auto Lod=MakeShared<FJsonObject>(); Lod->SetObjectField(TEXT("model"),ModelProperties(Mesh->GetSourceModel(I),Mesh));
        auto Desc=Mesh->GetMeshDescription(I);
        if(Desc)
        {
            TArray<uint8> Bytes; FMemoryWriter Writer(Bytes); if(!Geometry(*Desc,Writer)) {Error=TEXT("Unsupported mesh topology");return false;}
            FString File=FString::Printf(TEXT("mesh-%s-lod-%d.bin"),*FGuid::NewGuid().ToString(EGuidFormats::Digits),I);
            if(!FFileHelper::SaveArrayToFile(Bytes,*(Root/File))) {Error=TEXT("Cannot write mesh geometry");return false;}
            Lod->SetStringField(TEXT("payload"),File);
        }
        Lods.Add(MakeShared<FJsonValueObject>(Lod));
    }
    if(Mesh->IsHiResMeshDescriptionValid())
    {
        auto Desc=Mesh->GetHiResMeshDescription();TArray<uint8> Bytes;FMemoryWriter Writer(Bytes);
        if(!Desc||!Geometry(*Desc,Writer)){Error=TEXT("Invalid high-resolution source geometry");return false;}
        auto High=MakeShared<FJsonObject>();FString File=TEXT("mesh-hires-")+FGuid::NewGuid().ToString(EGuidFormats::Digits)+TEXT(".bin");High->SetStringField(TEXT("payload"),File);
        if(!FFileHelper::SaveArrayToFile(Bytes,*(Root/File))){Error=TEXT("Cannot write high-resolution geometry");return false;}Entry->SetObjectField(TEXT("hires"),High);
    }
    Entry->SetArrayField(TEXT("lods"),Lods);
    auto Body=Mesh->GetBodySetup();
    if(Body) { auto P=CyHubObjectIO::Properties(Body,true); P->RemoveField(TEXT("BodySetupGuid")); Entry->SetObjectField(TEXT("body"),P); Entry->SetStringField(TEXT("bodyName"),Body->GetName()); }
    TArray<TSharedPtr<FJsonValue>> Sockets;
    for(auto Socket : Mesh->Sockets) { auto Item=MakeShared<FJsonObject>();Item->SetStringField(TEXT("name"),Socket->GetName());Item->SetObjectField(TEXT("properties"),CyHubObjectIO::Properties(Socket,true));Sockets.Add(MakeShared<FJsonValueObject>(Item)); }
    Entry->SetArrayField(TEXT("sockets"),Sockets);
    Entry->SetObjectField(TEXT("sections"),CyHubObjectIO::StructProperties(FMeshSectionInfoMap::StaticStruct(),&Mesh->GetSectionInfoMap(),&GetDefault<UStaticMesh>()->GetSectionInfoMap(),Mesh));
    Entry->SetObjectField(TEXT("originalSections"),CyHubObjectIO::StructProperties(FMeshSectionInfoMap::StaticStruct(),&Mesh->GetOriginalSectionInfoMap(),&GetDefault<UStaticMesh>()->GetOriginalSectionInfoMap(),Mesh));
    return true;
}
