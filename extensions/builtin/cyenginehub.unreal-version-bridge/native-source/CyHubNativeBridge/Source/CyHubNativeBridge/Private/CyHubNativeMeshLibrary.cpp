bool UCyHubNativeMeshLibrary::Run(const FString& ConfigFile)
{
    auto Config=Read(ConfigFile); if(!Config)return false;
    const FString Root=Config->GetStringField(TEXT("exchangeRoot")),Op=Config->GetStringField(TEXT("operation"));
    TArray<TSharedPtr<FJsonValue>> Entries,Imported,Errors,Adaptations;
    auto Fail=[&](const FString& E){Errors.Add(MakeShared<FJsonValueString>(E));UE_LOG(LogTemp,Error,TEXT("%s"),*E);};
    if(Op==TEXT("export"))
    {
        auto Plan=Read(Config->GetStringField(TEXT("planPath")));
        if(!Plan || !Plan->GetBoolField(TEXT("canConvert"))) Fail(TEXT("Blocked mesh plan"));
        else for(auto Value : Plan->GetArrayField(TEXT("assets")))
        {
            FString Path=Value->AsObject()->GetStringField(TEXT("assetPath")),Error;
            if(!Valid(Path) || Value->AsObject()->GetStringField(TEXT("adapter"))!=TEXT("native-mesh-v1")) {Fail(TEXT("Invalid mesh plan entry"));break;}
            auto Entry=MakeShared<FJsonObject>();if(!Snapshot(LoadObject<UStaticMesh>(nullptr,*Path),Root,Entry,Error)){Fail(Path+TEXT(": ")+Error);break;} Entries.Add(MakeShared<FJsonValueObject>(Entry));
        }
        auto Manifest=MakeShared<FJsonObject>();Manifest->SetNumberField(TEXT("schemaVersion"),1);Manifest->SetArrayField(TEXT("assets"),Entries);if(!Write(Root/TEXT("native-meshes.json"),Manifest))Fail(TEXT("Cannot write mesh manifest"));
    }
    else if(Op==TEXT("import") || Op==TEXT("verify"))
    {
        auto Manifest=Read(Root/TEXT("native-meshes.json"));
        if(!Manifest || Manifest->GetIntegerField(TEXT("schemaVersion"))!=1)Fail(TEXT("Invalid mesh manifest"));
        else for(auto Value : Manifest->GetArrayField(TEXT("assets")))
        {
            auto Entry=Value->AsObject();FString Path=Entry->GetStringField(TEXT("path")),Error;UStaticMesh* Mesh=nullptr;
            if(!Valid(Path)){Fail(TEXT("Invalid mesh path"));break;}
            if(Op==TEXT("import"))
            {
                FString Pkg,Name;Path.Split(TEXT("."),&Pkg,&Name);if(FPackageName::DoesPackageExist(Pkg)){Fail(TEXT("Refusing mesh overwrite"));break;}
                Mesh=NewObject<UStaticMesh>(CreatePackage(*Pkg),*Name,RF_Public|RF_Standalone);
                Mesh->SetNumSourceModels(Entry->GetArrayField(TEXT("lods")).Num());
                if(!CyHubObjectIO::Apply(Mesh,Entry->GetObjectField(TEXT("properties")),Adaptations,Error)){Fail(Path+TEXT(": ")+Error);break;}
                const TSharedPtr<FJsonObject>* Body=nullptr;
                if(Entry->TryGetObjectField(TEXT("body"),Body)) {Mesh->SetBodySetup(NewObject<UBodySetup>(Mesh,*Entry->GetStringField(TEXT("bodyName"))));if(!CyHubObjectIO::Apply(Mesh->GetBodySetup(),*Body,Adaptations,Error)){Fail(Error);break;}}
                for(auto S : Entry->GetArrayField(TEXT("sockets"))) { auto Socket=NewObject<UStaticMeshSocket>(Mesh,*S->AsObject()->GetStringField(TEXT("name"))); if(!CyHubObjectIO::Apply(Socket,S->AsObject()->GetObjectField(TEXT("properties")),Adaptations,Error)){Fail(Error);break;} Mesh->Sockets.Add(Socket); }
                auto& Lods=Entry->GetArrayField(TEXT("lods"));
                for(int32 I=0;I<Lods.Num();++I) {auto Lod=Lods[I]->AsObject();if(!CyHubObjectIO::ApplyStruct(FStaticMeshSourceModel::StaticStruct(),&Mesh->GetSourceModel(I),Mesh,Lod->GetObjectField(TEXT("model")),Adaptations,Error)){Fail(Error);break;}if(Lod->HasField(TEXT("payload"))){if(!Payload(Root,Lod,Mesh->CreateMeshDescription(I),true,Error)){Fail(Error);break;}Mesh->CommitMeshDescription(I);}}
                if(!Errors.IsEmpty())break;
                const TSharedPtr<FJsonObject>* High=nullptr;if(Entry->TryGetObjectField(TEXT("hires"),High)){if(!Payload(Root,*High,Mesh->CreateHiResMeshDescription(),true,Error)){Fail(Error);break;}Mesh->CommitHiResMeshDescription();}
                if(!CyHubObjectIO::ApplyStruct(FMeshSectionInfoMap::StaticStruct(),&Mesh->GetSectionInfoMap(),Mesh,Entry->GetObjectField(TEXT("sections")),Adaptations,Error)){Fail(Error);break;}
                if(!CyHubObjectIO::ApplyStruct(FMeshSectionInfoMap::StaticStruct(),&Mesh->GetOriginalSectionInfoMap(),Mesh,Entry->GetObjectField(TEXT("originalSections")),Adaptations,Error)){Fail(Error);break;}
                Mesh->Build(true);FAssetCompilingManager::Get().FinishAllCompilation();Mesh->CreateNavCollision(true);FAssetRegistryModule::AssetCreated(Mesh);
                auto Package=Mesh->GetOutermost();Package->MarkPackageDirty();FString Filename=FPackageName::LongPackageNameToFilename(Pkg,FPackageName::GetAssetPackageExtension());IFileManager::Get().MakeDirectory(*FPaths::GetPath(Filename),true);FSavePackageArgs Args;Args.TopLevelFlags=RF_Public|RF_Standalone;Args.SaveFlags=SAVE_NoError;
                if(!UPackage::SavePackage(Package,Mesh,*Filename,Args)){Fail(TEXT("Mesh SavePackage failed"));break;}
            }
            else Mesh=LoadObject<UStaticMesh>(nullptr,*Path);
            if(!Mesh || Mesh->GetNumSourceModels()!=Entry->GetArrayField(TEXT("lods")).Num() || !CyHubObjectIO::Compare(Mesh,Entry->GetObjectField(TEXT("properties")),Error)){Fail(Path+TEXT(": ")+Error);break;}
            if(Entry->HasField(TEXT("renderLODs")))
            {
                auto& Expected=Entry->GetArrayField(TEXT("renderLODs"));auto Render=Mesh->GetRenderData();
                if(!Render||Render->LODResources.Num()!=Expected.Num()||(Entry->GetBoolField(TEXT("naniteData"))&&!Mesh->HasValidNaniteData())){Fail(FString::Printf(TEXT("Missing target render LOD/Nanite data: %s LODs %d/%d Nanite %d/%d"),*Path,Render?Render->LODResources.Num():0,Expected.Num(),Mesh->HasValidNaniteData(),Entry->GetBoolField(TEXT("naniteData"))));break;}
                for(int32 I=0;I<Expected.Num();++I)
                {
                    auto& Lod=Render->LODResources[I];if(Lod.GetNumTriangles()<=0||Lod.GetNumVertices()<=0){Fail(TEXT("Empty target render LOD"));break;}
                    if(Lod.GetNumTriangles()!=Expected[I]->AsObject()->GetIntegerField(TEXT("triangles"))||Lod.GetNumVertices()!=Expected[I]->AsObject()->GetIntegerField(TEXT("vertices")))
                        Adaptations.Add(MakeShared<FJsonValueString>(FString::Printf(TEXT("%s LOD%d: target derived geometry rebuilt (%d vertices, %d triangles; source %d / %d). Source geometry and reduction settings preserved."),*Path,I,Lod.GetNumVertices(),Lod.GetNumTriangles(),Expected[I]->AsObject()->GetIntegerField(TEXT("vertices")),Expected[I]->AsObject()->GetIntegerField(TEXT("triangles")))));
                }
            }
            for(int32 I=0;I<Mesh->GetNumSourceModels();++I) {auto Lod=Entry->GetArrayField(TEXT("lods"))[I]->AsObject();if(!CyHubObjectIO::CompareStruct(FStaticMeshSourceModel::StaticStruct(),&Mesh->GetSourceModel(I),Mesh,Lod->GetObjectField(TEXT("model")),Error) || (Lod->HasField(TEXT("payload")) && !Payload(Root,Lod,Mesh->GetMeshDescription(I),false,Error))){Fail(Path+TEXT(": ")+Error);break;}}
            const TSharedPtr<FJsonObject>* High=nullptr;if(Entry->TryGetObjectField(TEXT("hires"),High)&&!Payload(Root,*High,Mesh->GetHiResMeshDescription(),false,Error)){Fail(Error);break;}
            const TSharedPtr<FJsonObject>* Body=nullptr;if(Entry->TryGetObjectField(TEXT("body"),Body)&&(!Mesh->GetBodySetup()||!CyHubObjectIO::Compare(Mesh->GetBodySetup(),*Body,Error))){Fail(TEXT("Mesh collision: ")+Error);break;}
            if(Mesh->Sockets.Num()!=Entry->GetArrayField(TEXT("sockets")).Num()){Fail(TEXT("Mesh socket count mismatch"));break;}
            for(auto S:Entry->GetArrayField(TEXT("sockets"))){auto Socket=FindObject<UStaticMeshSocket>(Mesh,*S->AsObject()->GetStringField(TEXT("name")));if(!Socket||!CyHubObjectIO::Compare(Socket,S->AsObject()->GetObjectField(TEXT("properties")),Error)){Fail(TEXT("Mesh socket: ")+Error);break;}}
            if(!CheckSections(Mesh->GetSectionInfoMap(),Entry->GetObjectField(TEXT("sections")),Mesh,Adaptations,Error)||!CheckSections(Mesh->GetOriginalSectionInfoMap(),Entry->GetObjectField(TEXT("originalSections")),Mesh,Adaptations,Error)){Fail(TEXT("Mesh section/material mapping: ")+Error);break;}
            if(!Errors.IsEmpty())break;Imported.Add(MakeShared<FJsonValueString>(Path));
        }
    }
    else Fail(TEXT("Unknown mesh operation"));
    if(Entries.IsEmpty() && Imported.IsEmpty())Fail(TEXT("No mesh processed"));
    auto Report=MakeShared<FJsonObject>();Report->SetArrayField(TEXT("exported"),Entries);Report->SetArrayField(TEXT("imported"),Imported);Report->SetArrayField(TEXT("errors"),Errors);Report->SetArrayField(TEXT("adaptations"),Adaptations);Report->SetArrayField(TEXT("unsupported"),{});
    return Write(Config->GetStringField(TEXT("reportPath")),Report) && Errors.IsEmpty();
}
